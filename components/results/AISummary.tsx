'use client';

/**
 * AISummary — The ~100-word personalized paragraph from Anthropic.
 *
 * States:
 * - summary === null  → skeleton loading (3 lines)
 * - summary !== null  → rendered paragraph
 *
 * aria-live="polite" ensures the paragraph is announced when it loads
 * without interrupting the user if they are navigating the rest of the page.
 */

import { Skeleton } from '@/components/ui/skeleton';

interface AISummaryProps {
  summary: string | null;
}

export function AISummary({ summary }: AISummaryProps) {
  return (
    <section aria-labelledby="ai-summary-heading">
      <div className="mb-4">
        <h2
          id="ai-summary-heading"
          className="font-mono text-xs font-bold uppercase tracking-[0.2em] text-neutral-500"
        >
          Analysis
        </h2>
      </div>

      <div
        className="rounded-xl border border-white/8 bg-white/[0.025] p-5"
        aria-live="polite"
        aria-atomic="true"
        aria-label={summary ? 'AI analysis of your audit' : 'AI analysis is loading'}
      >
        {summary === null ? (
          // Loading skeleton — matches typical paragraph structure
          <div className="space-y-3" aria-hidden="true">
            <Skeleton className="h-4 w-full bg-white/8" />
            <Skeleton className="h-4 w-11/12 bg-white/8" />
            <Skeleton className="h-4 w-4/5 bg-white/8" />
          </div>
        ) : (
          <p className="text-sm leading-relaxed text-neutral-300">{summary}</p>
        )}

        {/* Attribution */}
        {summary !== null && (
          <p className="mt-4 font-mono text-[10px] text-neutral-700">
            Generated by Claude — Anthropic
          </p>
        )}
      </div>
    </section>
  );
}
